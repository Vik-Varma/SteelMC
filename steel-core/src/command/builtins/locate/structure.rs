//! `/locate structure`.
//!
//! Follows vanilla 26.3's `ChunkGenerator.findNearestMapStructure`. Like vanilla's
//! `StructureCheck`, a candidate chunk is only generated when its structure starts are not
//! already in memory and one of the requested structures could start there; that check runs
//! on the server's locate search pool, and each placement scan generates one chunk at a time
//! until it finds a start, as vanilla's scans stop at their first find.
//!
//! Unlike vanilla, a saved chunk that is not loaded is not read for its starts: the check
//! decides it, and the chunk is loaded only if the check passes. The two agree for chunks
//! generated by this generator.

use std::{
    sync::{
        Arc,
        atomic::{AtomicBool, Ordering},
    },
    time::Instant,
};

use steel_utils::{BlockPos, Identifier, translations};
use text_components::TextComponent;
use tokio::sync::oneshot;

