const MAX_STRUCTURE_SEARCH_RADIUS: i32 = 100;

pub(super) fn start_search(
    context: &SteelCommandContext<CommandSource>,
) -> Result<LocateStructureSearch, CommandSyntaxError> {
    let query = context.structure_or_tag_key("structure")?;
    let Some(structures) = query.resolve() else {
        return Err(invalid_structure(query));
    };
    if structures.is_empty() {
        return Err(structure_not_found(query));
    }

    let world = context.source().world();
    let Some(structure_generator) = world
        .chunk_map
        .world_gen_context
        .generator
        .structure_generator()
    else {
        return Err(structure_not_found(query));
    };
    let structure_keys = structures
        .iter()
        .map(|structure| structure.key.clone())
        .collect::<Vec<_>>();
    let Some(plan) = structure_generator.locate_plan_for_structures(&structure_keys) else {
        return Err(structure_not_found(query));
    };
    if plan.is_empty() {
        return Err(structure_not_found(query));
    }

    Ok(LocateStructureSearch {
        source: context.source().clone(),
        world: Arc::clone(world),
        query: query.clone(),
        plan: Arc::new(plan),
        origin: BlockPos::from(context.source().position()),
        phase: LocatePhase::Start,
        stage: Stage::Rings,
        check: None,
        scans: Vec::new(),
        best: None,
        random_radius: 0,
        cancelled: Arc::new(AtomicBool::new(false)),
        started_at: Instant::now(),
    })
}

enum LocatePhase {
    /// Collect the ring candidates.
    Start,
    /// Collect the next random-spread shell's candidates.
    RandomSpread,
    /// Waiting for the presence checks of the current stage's candidates.
    Checking,
    /// Generating candidate chunks, one per scan at a time.
    Resolving,
}

#[derive(Clone, Copy)]
enum Stage {
    Rings,
    RandomSpreadShell,
}

/// What a candidate chunk is known to hold before it is generated.
#[derive(Debug, Clone, PartialEq, Eq)]
enum CandidateCheck {
    /// The chunk's starts are in memory, and this requested structure starts there.
    Present(Identifier),
    /// No requested structure starts there, or none could.
    Absent,
    /// These requested structures could start there, so the chunk must be generated to know.
    NeedsChunk(Vec<Identifier>),
}

/// One placement's candidates in vanilla's order, resolved until the first find.
struct Scan {
    candidates: Vec<(StructureLocateCandidate, CandidateCheck)>,
    next: usize,
    pending: Option<ChunkRequestHandle>,
    found: Option<LocatedStructure>,
}

struct PendingCheck {
    candidates: Vec<StructureLocateCandidate>,
    receiver: oneshot::Receiver<Vec<CandidateCheck>>,
}

struct LocatedStructure {
    candidate: StructureLocateCandidate,
    found_structure: Identifier,
    distance_sqr: i64,
}

pub(super) struct LocateStructureSearch {
    source: CommandSource,
    world: Arc<World>,
    query: StructureOrTagKey,
    plan: Arc<StructureLocatePlan>,
    origin: BlockPos,
    phase: LocatePhase,
    stage: Stage,
    check: Option<PendingCheck>,
    scans: Vec<Scan>,
    best: Option<LocatedStructure>,
    random_radius: i32,
    cancelled: Arc<AtomicBool>,
    started_at: Instant,
}

impl CommandResultSuspension for LocateStructureSearch {
    fn poll(&mut self) -> CommandResultSuspensionPoll {
        loop {
            match self.phase {
                LocatePhase::Start => {
                    let candidates = self.plan.ring_candidates(self.origin);
                    if candidates.is_empty() {
                        self.phase = LocatePhase::RandomSpread;
                        continue;
                    }
                    self.start_check(Stage::Rings, candidates);
                    return CommandResultSuspensionPoll::Pending;
                }
                LocatePhase::RandomSpread => {
                    if self.random_radius > MAX_STRUCTURE_SEARCH_RADIUS {
                        return self.finished_result();
                    }

                    let candidates = self
                        .plan
                        .random_spread_candidates_at_radius(self.origin, self.random_radius);
                    self.random_radius += 1;

                    if candidates.is_empty() {
                        continue;
                    }
                    self.start_check(Stage::RandomSpreadShell, candidates);
                    return CommandResultSuspensionPoll::Pending;
                }
                LocatePhase::Checking => {
                    let Some(check) = &mut self.check else {
                        return Self::cancelled_result();
                    };
                    let checks = match check.receiver.try_recv() {
                        Ok(checks) => checks,
                        Err(oneshot::error::TryRecvError::Empty) => {
                            return CommandResultSuspensionPoll::Pending;
                        }
                        Err(oneshot::error::TryRecvError::Closed) => {
                            return Self::cancelled_result();
                        }
                    };
                    let Some(check) = self.check.take() else {
                        return Self::cancelled_result();
                    };
                    self.scans = scans(check.candidates, checks);
                    self.phase = LocatePhase::Resolving;
                }
                LocatePhase::Resolving => match self.resolve_scans() {
                    PendingRequest::Pending => return CommandResultSuspensionPoll::Pending,
                    PendingRequest::Cancelled => return Self::cancelled_result(),
                    PendingRequest::Ready => {
                        let found_any = self.take_scan_results();
                        match self.stage {
                            Stage::Rings => {
                                if self.best.is_some() && !self.plan.has_random_spread() {
                                    return self.success_result();
                                }
                            }
                            Stage::RandomSpreadShell => {
                                if found_any {
                                    return self.success_result();
                                }
                            }
                        }
                        self.phase = LocatePhase::RandomSpread;
                    }
                },
            }
        }
    }

    fn cancel(&mut self) {
        self.cancelled.store(true, Ordering::Relaxed);
        for scan in &mut self.scans {
            if let Some(pending) = &mut scan.pending {
                pending.cancel();
            }
        }
    }
}

impl LocateStructureSearch {
    /// Checks `candidates` on the locate search pool, off the server thread.
    fn start_check(&mut self, stage: Stage, candidates: Vec<StructureLocateCandidate>) {
        let (sender, receiver) = oneshot::channel();
        let world = Arc::clone(&self.world);
        let plan = Arc::clone(&self.plan);
        let cancelled = Arc::clone(&self.cancelled);
        let to_check = candidates.clone();
        self.source.server().locate_search_pool.spawn(move || {
            let mut checks = Vec::with_capacity(to_check.len());
            for candidate in to_check {
                // Dropping the sender ends the search as cancelled.
                if cancelled.load(Ordering::Relaxed) {
                    return;
                }
                checks.push(check_candidate(&world, &plan, candidate));
            }
            let _ = sender.send(checks);
        });
        self.stage = stage;
        self.check = Some(PendingCheck {
            candidates,
            receiver,
        });
        self.phase = LocatePhase::Checking;
    }

    /// Advances every unfinished scan until it finds a start, runs out of candidates, or
    /// waits on a chunk.
    fn resolve_scans(&mut self) -> PendingRequest {
        let mut waiting = false;
        for index in 0..self.scans.len() {
            match self.resolve_scan(index) {
                PendingRequest::Pending => waiting = true,
                PendingRequest::Cancelled => return PendingRequest::Cancelled,
                PendingRequest::Ready => {}
            }
        }
        if waiting {
            PendingRequest::Pending
        } else {
            PendingRequest::Ready
        }
    }

    fn resolve_scan(&mut self, index: usize) -> PendingRequest {
        loop {
            let scan = &mut self.scans[index];
            if scan.found.is_some() {
                return PendingRequest::Ready;
            }
            let Some((candidate, check)) = scan.candidates.get(scan.next).cloned() else {
                return PendingRequest::Ready;
            };
            let found_structure = match check {
                CandidateCheck::Absent => None,
                CandidateCheck::Present(structure) => Some(structure),
                CandidateCheck::NeedsChunk(structures) => {
                    let Some(pending) = &scan.pending else {
                        scan.pending = Some(self.world.chunk_map.request_chunks(ChunkRequest {
                            status: ChunkStatus::StructureStarts,
                            positions: vec![candidate.chunk_pos],
                            ticket_kind: ChunkTicketKind::StructureLocate,
                        }));
                        return PendingRequest::Pending;
                    };
                    match pending.poll() {
                        ChunkRequestState::Pending { .. } => return PendingRequest::Pending,
                        ChunkRequestState::Cancelled => return PendingRequest::Cancelled,
                        ChunkRequestState::Ready => {}
                    }
                    let found = self.generated_structure_at(candidate, &structures);
                    // Releases the chunk's locate ticket.
                    self.scans[index].pending = None;
                    found
                }
            };
            let scan = &mut self.scans[index];
            match found_structure {
                Some(found_structure) => {
                    scan.found = Some(LocatedStructure {
                        candidate,
                        found_structure,
                        distance_sqr: squared_distance(candidate.locate_pos, self.origin),
                    });
                }
                None => scan.next += 1,
            }
        }
    }

    /// Moves the scans' finds into `best`, keeping the earliest scan's find on ties.
    /// Returns whether any scan found a start.
    fn take_scan_results(&mut self) -> bool {
        let mut found_any = false;
        for scan in self.scans.drain(..) {
            let Some(located) = scan.found else {
                continue;
            };
            found_any = true;
            if self
                .best
                .as_ref()
                .is_none_or(|current| located.distance_sqr < current.distance_sqr)
            {
                self.best = Some(located);
            }
        }
        found_any
    }

    fn generated_structure_at(
        &self,
        candidate: StructureLocateCandidate,
        structures: &[Identifier],
    ) -> Option<Identifier> {
        let holder = self
            .world
            .chunk_map
            .chunks
            .read_sync(&candidate.chunk_pos, |_, holder| Arc::clone(holder))?;
        let chunk = holder.try_chunk(ChunkStatus::StructureStarts)?;
        first_started_structure(chunk, structures)
    }

    fn finished_result(&self) -> CommandResultSuspensionPoll {
        if self.best.is_some() {
            self.success_result()
        } else {
            CommandResultSuspensionPoll::Ready(Err(structure_not_found(&self.query)))
        }
    }

    fn success_result(&self) -> CommandResultSuspensionPoll {
        let Some(best) = &self.best else {
            return CommandResultSuspensionPoll::Ready(Err(structure_not_found(&self.query)));
        };
        let distance = show_locate_result(
            &self.source,
            self.origin,
            best.candidate.locate_pos,
            &translations::COMMANDS_LOCATE_STRUCTURE_SUCCESS,
            false,
            &self.query.found_name(&best.found_structure),
            self.started_at.elapsed(),
        );
        CommandResultSuspensionPoll::Ready(Ok(distance))
    }

    fn cancelled_result() -> CommandResultSuspensionPoll {
        CommandResultSuspensionPoll::Ready(Err(CommandSyntaxError::dynamic(
            "Structure search was cancelled",
        )))
    }
}

impl Drop for LocateStructureSearch {
    fn drop(&mut self) {
        self.cancelled.store(true, Ordering::Relaxed);
    }
}

/// Groups checked candidates into scans, keeping each scan's candidates in order.
fn scans(candidates: Vec<StructureLocateCandidate>, checks: Vec<CandidateCheck>) -> Vec<Scan> {
    let mut scans: Vec<(usize, Scan)> = Vec::new();
    for (candidate, check) in candidates.into_iter().zip(checks) {
        let scan_id = candidate.scan_id();
        let index = if let Some(index) = scans.iter().position(|(id, _)| *id == scan_id) {
            index
        } else {
            scans.push((
                scan_id,
                Scan {
                    candidates: Vec::new(),
                    next: 0,
                    pending: None,
                    found: None,
                },
            ));
            scans.len() - 1
        };
        scans[index].1.candidates.push((candidate, check));
    }
    scans.sort_by_key(|(scan_id, _)| *scan_id);
    scans.into_iter().map(|(_, scan)| scan).collect()
}

/// Vanilla's `StructureCheck.checkStart` for a candidate, over every requested structure of
/// its scan.
fn check_candidate(
    world: &World,
    plan: &StructureLocatePlan,
    candidate: StructureLocateCandidate,
) -> CandidateCheck {
    let Some(structures) = plan.structures_for_candidate(candidate) else {
        return CandidateCheck::Absent;
    };
    let holder = world
        .chunk_map
        .chunks
        .read_sync(&candidate.chunk_pos, |_, holder| Arc::clone(holder));
    if let Some(chunk) = holder
        .as_deref()
        .and_then(|holder| holder.try_chunk(ChunkStatus::StructureStarts))
    {
        return first_started_structure(chunk, structures)
            .map_or(CandidateCheck::Absent, CandidateCheck::Present);
    }

    let Some(placement) = plan.placement_for_candidate(candidate) else {
        return CandidateCheck::Absent;
    };
    let world_gen = &world.chunk_map.world_gen_context;
    let possible: Vec<Identifier> = structures
        .iter()
        .filter(|structure| {
            world_gen.generator.could_start_structure(
                candidate.chunk_pos,
                world_gen.min_y(),
                world_gen.height(),
                placement,
                structure,
            )
        })
        .cloned()
        .collect();
    if possible.is_empty() {
        CandidateCheck::Absent
    } else {
        CandidateCheck::NeedsChunk(possible)
    }
}

/// The first of `structures` with a valid start in `chunk`.
fn first_started_structure(chunk: &Chunk, structures: &[Identifier]) -> Option<Identifier> {
    let starts = chunk.structure_starts();
    structures
        .iter()
        .find(|structure| {
            starts
                .get(*structure)
                .is_some_and(|start| !start.pieces.is_empty())
        })
        .cloned()
}

enum PendingRequest {
    Pending,
    Ready,
    Cancelled,
}

fn invalid_structure(query: &StructureOrTagKey) -> CommandSyntaxError {
    CommandSyntaxError::dynamic(
        translations::COMMANDS_LOCATE_STRUCTURE_INVALID
            .message([TextComponent::from(query.as_printable())])
            .component(),
    )
}

fn structure_not_found(query: &StructureOrTagKey) -> CommandSyntaxError {
    CommandSyntaxError::dynamic(
        translations::COMMANDS_LOCATE_STRUCTURE_NOT_FOUND
            .message([TextComponent::from(query.as_printable())])
            .component(),
    )
}

#[cfg(test)]
mod tests {
    use std::{slice, thread};

    use steel_utils::{BlockPos, Identifier, threading::DEBUG_STACK_SIZE};

    use super::{CandidateCheck, check_candidate};
    use crate::{
        test_support::{fresh_flat_world_with_structure_sets, insert_ready_full_chunk},
        worldgen::generator::ChunkGenerator,
    };

    #[test]
    fn a_chunk_in_memory_is_judged_by_its_starts_not_by_whether_one_could_start() {
        // Structure generators overflow the default test stack in debug builds.
        thread::Builder::new()
            .stack_size(DEBUG_STACK_SIZE)
            .spawn(|| {
                let world_fixture = fresh_flat_world_with_structure_sets(
                    "locate-structure-in-memory",
                    7,
                    &["villages"],
                );
                let world = &world_fixture.world;
                let village = Identifier::vanilla_static("village_plains");
                let Some(plan) = world
                    .chunk_map
                    .world_gen_context
                    .generator
                    .structure_generator()
                    .and_then(|generator| {
                        generator.locate_plan_for_structures(slice::from_ref(&village))
                    })
                else {
                    panic!("plains villages can occur");
                };
                let candidate =
                    plan.random_spread_candidates_at_radius(BlockPos::new(0, 64, 0), 0)[0];

                // A village fits anywhere on flat plains, so the chunk must be generated.
                assert_eq!(
                    check_candidate(world, &plan, candidate),
                    CandidateCheck::NeedsChunk(vec![village])
                );
                // The structure's own search checks its biomes: no desert village can start
                // on plains, although desert villages share the placement.
                let world_gen = &world.chunk_map.world_gen_context;
                let Some(placement) = plan.placement_for_candidate(candidate) else {
                    panic!("candidates belong to the plan");
                };
                assert!(!world_gen.generator.could_start_structure(
                    candidate.chunk_pos,
                    world_gen.min_y(),
                    world_gen.height(),
                    placement,
                    &Identifier::vanilla_static("village_desert"),
                ));
                // Once its starts are in memory, they decide: this chunk has none.
                insert_ready_full_chunk(world, candidate.chunk_pos);
                assert_eq!(
                    check_candidate(world, &plan, candidate),
                    CandidateCheck::Absent
                );
            })
            .expect("test thread should spawn")
            .join()
            .expect("test thread panicked");
    }
}
